/**
 * 주식 클래스 판정 — 보통주인가, 우선주(또는 전환우선주 등 별도 클래스)인가.
 *
 * **KRX 종목코드는 보통주가 `0`으로 끝난다.** 우선주는 구형이 `5`·`7`·`9`, 신형이 `K`·`L`·`M`이고,
 * 앞 5자리는 보통주와 같다(삼성전자 005930 ↔ 삼성전자우 005935).
 *
 * 이름으로 판정하면 안 된다 — `성우`·`이오플로우`처럼 **이름이 '우'로 끝나는 보통주**가 있고,
 * 반대로 `CJ4우(전환)`·`아모레퍼시픽홀딩스3우C`처럼 흔한 접미사 규칙에서 벗어난 우선주도 있다.
 * 실측(2026-08-12, 활성 2,763종목): 코드 규칙으로 113종목이 잡히고 **113종목 전부** 앞 5자리가
 * 같은 보통주 짝을 갖는다. 이름 규칙은 오탐 3건·누락 3건이었다.
 *
 * ### 왜 필요한가 — 시총과 재무의 단위가 어긋난다
 *
 * `stocks.market_cap`은 **그 클래스만의 시총**인데 `stock_financials`의 이익은 **회사 전체**다.
 * 그래서 시총 ÷ 이익으로 만든 PER·POR이 우선주에서 통째로 무너진다 — 실측 결과 우선주 배수가
 * 보통주 대비 **중앙 32배, 최대 301배 낮게** 나왔다(NH투자증권우 0.45배 vs 보통주 10.15배).
 * "싼 순"으로 정렬하면 상단이 이 가짜 값으로 채워진다.
 */

/** 보통주가 아닌 클래스(우선주·전환우선주 등)인가. */
export function isPreferredShare(ticker: string): boolean {
  return ticker.length > 0 && !ticker.endsWith('0');
}

/** 같은 회사의 보통주 코드 — 앞 5자리 + `0`. */
export function commonShareTickerOf(ticker: string): string {
  return `${ticker.slice(0, 5)}0`;
}
